package server

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// syncPhotofieldConfig rewrites Photofield's configuration.yaml so its
// collections mirror the folders saved in the app. Only call this while the
// gallery is stopped — Photofield does not like its config changing mid-scan.
func (s *Server) syncPhotofieldConfig() error {
	if s.cfg.PhotofieldData == "" {
		return nil
	}
	libs := s.libs.available()
	if len(libs) == 0 {
		return nil
	}

	var b strings.Builder
	b.WriteString("# Generated by OCD Manager - these collections mirror your saved folders.\n")
	b.WriteString("# Read-only: browsing never modifies your files.\n")
	b.WriteString("collections:\n")
	for _, l := range libs {
		dir := filepath.ToSlash(l.Path)
		if !strings.HasSuffix(dir, "/") {
			dir += "/"
		}
		fmt.Fprintf(&b, "  - name: %q\n    layout: timeline\n    dirs:\n      - %q\n", l.Name, dir)
	}

	if err := os.MkdirAll(s.cfg.PhotofieldData, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(s.cfg.PhotofieldData, "configuration.yaml"), []byte(b.String()), 0o644)
}
